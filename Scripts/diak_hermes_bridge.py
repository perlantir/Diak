class BridgeState:
    """Tiny JSON state store for Diak sessions and captured stream events."""

    def __init__(self, path: Path | None = None, *, persist: bool = True):
        self.path = path or DEFAULT_STATE_PATH
        self.persist = persist
        self._lock = threading.RLock()
        self._data: dict[str, Any] = {"sessions": {}, "messages": {}, "events": {}, "connectors": {}, "artifacts": {}, "approvals": {}, "memory": {}, "automations": {}, "skills": {}, "skill_drafts": {}}
        if persist:
            self._load()

    def _load(self) -> None:
        try:
            if self.path.exists():
                loaded = json.loads(self.path.read_text(encoding="utf-8"))
                if isinstance(loaded, dict):
                    self._data["sessions"] = loaded.get("sessions", {}) if isinstance(loaded.get("sessions", {}), dict) else {}
                    self._data["messages"] = loaded.get("messages", {}) if isinstance(loaded.get("messages", {}), dict) else {}
                    self._data["events"] = loaded.get("events", {}) if isinstance(loaded.get("events", {}), dict) else {}
                    self._data["connectors"] = loaded.get("connectors", {}) if isinstance(loaded.get("connectors", {}), dict) else {}
                    self._data["artifacts"] = loaded.get("artifacts", {}) if isinstance(loaded.get("artifacts", {}), dict) else {}
                    self._data["approvals"] = loaded.get("approvals", {}) if isinstance(loaded.get("approvals", {}), dict) else {}
                    self._data["memory"] = loaded.get("memory", {}) if isinstance(loaded.get("memory", {}), dict) else {}
                    self._data["automations"] = loaded.get("automations", {}) if isinstance(loaded.get("automations", {}), dict) else {}
                    self._data["skills"] = loaded.get("skills", {}) if isinstance(loaded.get("skills", {}), dict) else {}
                    self._data["skill_drafts"] = loaded.get("skill_drafts", {}) if isinstance(loaded.get("skill_drafts", {}), dict) else {}
        except Exception:
            # Corrupt state must not prevent the bridge from starting.  Keep the
            # bad file for forensic inspection and begin with empty state.
            self._data = {"sessions": {}, "messages": {}, "events": {}, "connectors": {}, "artifacts": {}, "approvals": {}, "memory": {}, "automations": {}, "skills": {}, "skill_drafts": {}}

    def _save_locked(self) -> None:
        if not self.persist:
            return
        self.path.parent.mkdir(parents=True, exist_ok=True)
        fd, tmp_name = tempfile.mkstemp(prefix=self.path.name, suffix=".tmp", dir=str(self.path.parent))
        try:
            with os.fdopen(fd, "w", encoding="utf-8") as handle:
                json.dump(self._data, handle, ensure_ascii=False, indent=2, sort_keys=True)
                handle.write("\n")
            os.replace(tmp_name, self.path)
        finally:
            try:
                if os.path.exists(tmp_name):
                    os.unlink(tmp_name)
            except OSError:
                pass

    def list_sessions(self) -> list[dict[str, Any]]:
        with self._lock:
            return sorted(self._data["sessions"].values(), key=lambda s: s.get("updated_at", ""), reverse=True)

    def get_session(self, session_id: str) -> dict[str, Any] | None:
        with self._lock:
            session = self._data["sessions"].get(session_id)
            return dict(session) if isinstance(session, dict) else None

    def get_messages(self, session_id: str) -> list[dict[str, Any]]:
        with self._lock:
            return list(self._data["messages"].get(session_id, []))

    def get_events(self, session_id: str) -> list[dict[str, Any]]:
        with self._lock:
            return list(self._data["events"].get(session_id, []))

    def get_artifacts(self, session_id: str) -> list[dict[str, Any]]:
        with self._lock:
            return list(self._data["artifacts"].get(session_id, []))

    def upsert_session(self, session: dict[str, Any]) -> dict[str, Any]:
        with self._lock:
            self._data["sessions"][session["id"]] = dict(session)
            self._save_locked()
            return dict(session)

    def append_message(self, session_id: str, message: dict[str, Any]) -> None:
        with self._lock:
            self._data["messages"].setdefault(session_id, []).append(dict(message))
            self._save_locked()

    def set_events(self, session_id: str, events: list[dict[str, Any]]) -> None:
        with self._lock:
            self._data["events"][session_id] = list(events)
            self._save_locked()

    def append_events(self, session_id: str, events: list[dict[str, Any]]) -> None:
        with self._lock:
            self._data["events"].setdefault(session_id, []).extend(events)
            self._save_locked()

    def set_artifacts(self, session_id: str, artifacts: list[dict[str, Any]]) -> None:
        with self._lock:
            self._data["artifacts"][session_id] = list(artifacts)
            self._save_locked()


