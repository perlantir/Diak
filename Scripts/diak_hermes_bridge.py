def utc_now() -> str:
    return datetime.now(timezone.utc).replace(microsecond=0).isoformat().replace("+00:00", "Z")


def json_dumps(payload: Any) -> str:
    return json.dumps(payload, ensure_ascii=False, separators=(",", ":"))


def make_id(prefix: str) -> str:
    return f"{prefix}-{uuid.uuid4().hex[:16]}"


def title_from_prompt(prompt: str) -> str:
    squashed = re.sub(r"\s+", " ", prompt).strip()
    if not squashed:
        return "New Hermes session"
    return squashed[:80]


def _strip_markdown_fence(text: str) -> str:
    match = re.search(r"```(?:html|HTML)?\s*(.*?)```", text, flags=re.DOTALL)
    return match.group(1).strip() if match else text.strip()


def artifact_from_response(session_id: str, prompt: str, response: str) -> dict[str, Any] | None:
    """Best-effort typed canvas artifact extraction for real Hermes responses.

    The production bridge does not execute browser/code tools itself. When the
    real Hermes runtime returns website/canvas-shaped content, preserve it as a
    typed Diak artifact so the Mac app can render the result in Canvas instead
    of leaving the response trapped in chat text.
    """
    haystack = f"{prompt}\n{response}".lower()
    if not any(token in haystack for token in ("canvas", "website", "html", "landing page", "marketing site")):
        return None
    body = _strip_markdown_fence(response)
    kind = "browser" if ("<html" in body.lower() or "<!doctype" in body.lower() or "website" in haystack) else "document"
    title = "Generated website" if kind == "browser" else title_from_prompt(prompt)
    return {
        "id": make_id("canvas-art"),
        "session_id": session_id,
        "kind": kind,
        "title": title,
        "summary": "Generated by the real Hermes Agent runtime through the production bridge.",
        "preview": body[:20000],
        "created_at": utc_now(),
        "ref": {"id": make_id("generated"), "kind": "generated", "title": title, "detail": "production_bridge"},
    }


